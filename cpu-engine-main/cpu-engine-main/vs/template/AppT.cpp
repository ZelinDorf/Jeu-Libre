void App::OnStart()
{
	// YOUR CODE HERE
	
	//entity
	mp_player = new Player;
	mp_Enemy = new Enemy;


	m_materialMissile.ps = MyPixelShader;
	m_meshMissile.CreateSphere(0.5f);

	//camera
	cpuEngine.GetCamera()->transform.pos.z = -20.0f;
	cpuEngine.GetCamera()->transform.pos.y = 5.0f;
}

void App::OnUpdate()
{
	// YOUR CODE HERE

	float dt = cpuTime.delta;

	if (cpuInput.IsActionPressed() || cpuInput.IsAction(1))
		cpuApp.SpawnMissile();
	
	mp_player->OnUpdate(dt);
	mp_Enemy->OnUpdate(mp_player->GetEntity());

	for (auto it = m_missiles.begin(); it != m_missiles.end(); ++it)
	{
		cpu_entity* pMissile = *it;
		pMissile->transform.Move(dt * m_speed);
		if (pMissile->lifetime > 10.0f)
			cpuEngine.Release(pMissile);
	}
}

