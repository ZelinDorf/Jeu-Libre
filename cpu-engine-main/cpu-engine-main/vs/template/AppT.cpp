Player::Player()
{
	//mesh
	m_mesh.CreateSpaceship();

	//material
	m_material.color = CPU_ORANGE;

	//entity
	mp_entity = cpuEngine.CreateEntity();
	mp_entity->pMesh = &m_mesh;
	mp_entity->pMaterial = &m_material;
	mp_entity->transform.pos.x = 0.f;
	mp_entity->transform.pos.y = 1.f;
	mp_entity->transform.pos.z = 0.f;
}

void Player::Shoot()
{
	//jps
}

void Player::OnUpdate(float _dt)
{
	if (cpuInput.IsDown())
	{
		mp_entity->transform.pos.z -= 5.f * _dt;
	}
	if (cpuInput.IsUp())
	{
		mp_entity->transform.pos.z += 5.f * _dt;
	}
	if (cpuInput.IsLeft())
	{
		mp_entity->transform.pos.x -= 5.f * _dt;
		mp_entity->transform.AddYPR(5.f * -_dt);
	}
	if (cpuInput.IsRight())
	{
		mp_entity->transform.pos.x += 5.f * _dt;
		mp_entity->transform.AddYPR(5.f * _dt);
	}

}

