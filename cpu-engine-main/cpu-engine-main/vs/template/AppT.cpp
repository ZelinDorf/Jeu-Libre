Enemy::Enemy()
{
	m_mesh.CreateSpaceship();

	//material
	m_material.color = CPU_RED;

	//entity
	mp_entity = cpuEngine.CreateEntity();
	mp_entity->pMesh = &m_mesh;
	mp_entity->pMaterial = &m_material;
	mp_entity->transform.pos.x = 0.f;
	mp_entity->transform.pos.y = 1.f;
	mp_entity->transform.pos.z = 5.f;
}

void Enemy::Hit()
{
	Despawn();
}

void Enemy::OnUpdate(cpu_entity* player)
{
	float speed = 2.0f;
	float dt = cpuTime.delta;

	XMFLOAT3 playPos = player->transform.pos;

	mp_entity->transform.LookAt(playPos.x, playPos.y, playPos.z);

	mp_entity->transform.Move(dt * speed);
}

void Enemy::Despawn()
{
	mp_entity = cpuEngine.Release(mp_entity);
}
